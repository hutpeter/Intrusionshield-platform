-- PostgreSQL authorization foundation. Depends on 001_identity_foundation.sql.
-- Privileged provisioning only; no role or permission grants are seeded.
CREATE TABLE IF NOT EXISTS "Identity"."Permissions" (
    "Id" uuid PRIMARY KEY,
    "Name" varchar(200) NOT NULL,
    "Resource" varchar(150) NOT NULL,
    "Action" varchar(100) NOT NULL,
    "Scope" varchar(20) NOT NULL CHECK ("Scope" IN ('PLATFORM','TENANT')),
    CONSTRAINT "UQ_PermissionResourceActionScope" UNIQUE ("Resource","Action","Scope"),
    CONSTRAINT "UQ_PermissionIdScope" UNIQUE ("Id","Scope")
);
CREATE TABLE IF NOT EXISTS "Identity"."Roles" (
    "Id" uuid PRIMARY KEY,
    "TenantId" uuid NULL,
    "Name" varchar(200) NOT NULL,
    "Scope" varchar(20) NOT NULL,
    "CreatedAt" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "UQ_RoleIdScope" UNIQUE ("Id","Scope"),
    CONSTRAINT "UQ_RoleIdTenant" UNIQUE ("Id","TenantId"),
    CONSTRAINT "CK_RoleScopeTenant" CHECK (
        ("Scope" = 'PLATFORM' AND "TenantId" IS NULL) OR
        ("Scope" = 'TENANT' AND "TenantId" IS NOT NULL))
);
CREATE UNIQUE INDEX IF NOT EXISTS "UX_IdentityRoles_PlatformName"
    ON "Identity"."Roles" ("Name") WHERE "TenantId" IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS "UX_IdentityRoles_TenantName"
    ON "Identity"."Roles" ("TenantId","Name") WHERE "Scope" = 'TENANT';
CREATE TABLE IF NOT EXISTS "Identity"."RolePermissions" (
    "RoleId" uuid NOT NULL,
    "PermissionId" uuid NOT NULL,
    "Scope" varchar(20) NOT NULL,
    CONSTRAINT "PK_RolePermissions" PRIMARY KEY ("RoleId","PermissionId"),
    CONSTRAINT "FK_RolePermissions_Role" FOREIGN KEY ("RoleId","Scope")
        REFERENCES "Identity"."Roles" ("Id","Scope"),
    CONSTRAINT "FK_RolePermissions_Permission" FOREIGN KEY ("PermissionId","Scope")
        REFERENCES "Identity"."Permissions" ("Id","Scope")
);
CREATE TABLE IF NOT EXISTS "Identity"."IdentityRoles" (
    "TenantId" uuid NOT NULL,
    "IdentityId" uuid NOT NULL,
    "RoleId" uuid NOT NULL,
    "Scope" varchar(20) NOT NULL DEFAULT 'TENANT' CHECK ("Scope" = 'TENANT'),
    "AssignedAt" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "PK_IdentityRoles" PRIMARY KEY ("TenantId","IdentityId","RoleId"),
    CONSTRAINT "FK_IdentityRoles_Identity" FOREIGN KEY ("TenantId","IdentityId")
        REFERENCES "Identity"."Identities" ("TenantId","Id"),
    CONSTRAINT "FK_IdentityRoles_TenantRole" FOREIGN KEY ("RoleId","TenantId")
        REFERENCES "Identity"."Roles" ("Id","TenantId"),
    CONSTRAINT "FK_IdentityRoles_RoleScope" FOREIGN KEY ("RoleId","Scope")
        REFERENCES "Identity"."Roles" ("Id","Scope")
);
CREATE TABLE IF NOT EXISTS "Identity"."PlatformRoleAssignments" (
    "TenantId" uuid NOT NULL,
    "IdentityId" uuid NOT NULL,
    "RoleId" uuid NOT NULL,
    "Scope" varchar(20) NOT NULL DEFAULT 'PLATFORM' CHECK ("Scope" = 'PLATFORM'),
    "AssignedAt" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "PK_PlatformRoleAssignments" PRIMARY KEY ("TenantId","IdentityId","RoleId"),
    CONSTRAINT "FK_PlatformRoleAssignments_Identity" FOREIGN KEY ("TenantId","IdentityId")
        REFERENCES "Identity"."Identities" ("TenantId","Id"),
    CONSTRAINT "FK_PlatformRoleAssignments_Role" FOREIGN KEY ("RoleId","Scope")
        REFERENCES "Identity"."Roles" ("Id","Scope")
);
CREATE TABLE IF NOT EXISTS "Identity"."AuthorizationAudit" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "OccurredAt" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "TenantId" uuid NULL,
    "IdentityId" uuid NULL,
    "Resource" varchar(150) NOT NULL,
    "Action" varchar(100) NOT NULL,
    "Allowed" boolean NOT NULL,
    "Reason" varchar(500) NULL,
    "CorrelationId" varchar(100) NULL
);
CREATE INDEX IF NOT EXISTS "IX_IdentityAuthorizationAudit_OccurredAt"
    ON "Identity"."AuthorizationAudit" ("OccurredAt");
CREATE INDEX IF NOT EXISTS "IX_IdentityAuthorizationAudit_Identity"
    ON "Identity"."AuthorizationAudit" ("TenantId","IdentityId","OccurredAt");
-- Tenant-scoped authorization records cannot be read across tenant boundaries.
-- Platform role definitions are global; assignments are tenant-specific.
ALTER TABLE "Identity"."IdentityRoles" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "Identity"."IdentityRoles" FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "ruby_identity_roles_tenant" ON "Identity"."IdentityRoles";
CREATE POLICY "ruby_identity_roles_tenant" ON "Identity"."IdentityRoles"
    USING ("TenantId" = NULLIF(current_setting('ruby.tenant_id',true),'')::uuid)
    WITH CHECK ("TenantId" = NULLIF(current_setting('ruby.tenant_id',true),'')::uuid);
ALTER TABLE "Identity"."PlatformRoleAssignments" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "Identity"."PlatformRoleAssignments" FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "ruby_platform_assignments_tenant" ON "Identity"."PlatformRoleAssignments";
CREATE POLICY "ruby_platform_assignments_tenant" ON "Identity"."PlatformRoleAssignments"
    FOR SELECT USING ("TenantId" = NULLIF(current_setting('ruby.tenant_id',true),'')::uuid);
-- No INSERT/UPDATE/DELETE policies: platform assignments require a privileged role.
ALTER TABLE "Identity"."Roles" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "Identity"."Roles" FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "ruby_roles_read" ON "Identity"."Roles";
CREATE POLICY "ruby_roles_read" ON "Identity"."Roles"
    FOR SELECT USING ("Scope" = 'PLATFORM' OR
        "TenantId" = NULLIF(current_setting('ruby.tenant_id',true),'')::uuid);
-- Permission and role-permission catalogs require restricted grants and privileged writes.
ALTER TABLE "Identity"."AuthorizationAudit" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "Identity"."AuthorizationAudit" FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "ruby_audit_tenant" ON "Identity"."AuthorizationAudit";
CREATE POLICY "ruby_audit_tenant" ON "Identity"."AuthorizationAudit"
    USING ("TenantId" = NULLIF(current_setting('ruby.tenant_id',true),'')::uuid)
    WITH CHECK ("TenantId" = NULLIF(current_setting('ruby.tenant_id',true),'')::uuid);
